from datetime import datetime, timezone
from sqlalchemy import String, Text, DateTime, ForeignKey, Boolean, UniqueConstraint, Index, JSON, Numeric, Integer
from sqlalchemy.orm import Mapped, mapped_column, relationship
from .db import Base
def now(): return datetime.now(timezone.utc)
class Company(Base):
    __tablename__='companies'
    id: Mapped[int]=mapped_column(primary_key=True)
    name: Mapped[str]=mapped_column(String(200),unique=True,index=True)
    careers_url: Mapped[str|None]=mapped_column(String(1000),nullable=True)
    created_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now)
    sources: Mapped[list['Source']]=relationship(back_populates='company',cascade='all, delete-orphan')
class Source(Base):
    __tablename__='sources'
    id: Mapped[int]=mapped_column(primary_key=True)
    company_id: Mapped[int]=mapped_column(ForeignKey('companies.id',ondelete='CASCADE'),index=True)
    connector: Mapped[str]=mapped_column(String(30))
    board_token: Mapped[str]=mapped_column(String(300))
    active: Mapped[bool]=mapped_column(Boolean,default=True)
    last_run_at: Mapped[datetime|None]=mapped_column(DateTime(timezone=True),nullable=True)
    last_error: Mapped[str|None]=mapped_column(Text,nullable=True)
    company: Mapped[Company]=relationship(back_populates='sources')
    jobs: Mapped[list['Job']]=relationship(back_populates='source')
    __table_args__=(UniqueConstraint('connector','board_token',name='uq_source_board'),)
class Job(Base):
    __tablename__='jobs'
    id: Mapped[int]=mapped_column(primary_key=True)
    source_id: Mapped[int]=mapped_column(ForeignKey('sources.id',ondelete='CASCADE'),index=True)
    source_job_id: Mapped[str]=mapped_column(String(300))
    title: Mapped[str]=mapped_column(String(500),index=True)
    team_name: Mapped[str|None]=mapped_column(String(300),nullable=True)
    seniority: Mapped[str|None]=mapped_column(String(80),nullable=True)
    company_name: Mapped[str|None]=mapped_column(String(300),nullable=True,index=True)
    location: Mapped[str|None]=mapped_column(String(500),nullable=True,index=True)
    department: Mapped[str|None]=mapped_column(String(300),nullable=True)
    employment_type: Mapped[str|None]=mapped_column(String(100),nullable=True)
    description: Mapped[str|None]=mapped_column(Text,nullable=True)
    summary: Mapped[str|None]=mapped_column(Text,nullable=True)
    url: Mapped[str]=mapped_column(String(2000))
    posted_at: Mapped[str|None]=mapped_column(String(100),nullable=True)
    apply_url: Mapped[str|None]=mapped_column(String(2000),nullable=True)
    work_mode: Mapped[str|None]=mapped_column(String(40),nullable=True,index=True)
    location_city: Mapped[str|None]=mapped_column(String(200),nullable=True)
    location_region: Mapped[str|None]=mapped_column(String(200),nullable=True)
    location_country: Mapped[str|None]=mapped_column(String(200),nullable=True)
    eligible_countries: Mapped[list]=mapped_column(JSON,default=list)
    remote_scope: Mapped[str|None]=mapped_column(String(100),nullable=True)
    visa_sponsorship: Mapped[bool|None]=mapped_column(Boolean,nullable=True)
    relocation_available: Mapped[bool|None]=mapped_column(Boolean,nullable=True)
    timezone_requirements: Mapped[str|None]=mapped_column(String(300),nullable=True)
    salary_min: Mapped[float|None]=mapped_column(Numeric,nullable=True)
    salary_max: Mapped[float|None]=mapped_column(Numeric,nullable=True)
    salary_currency: Mapped[str|None]=mapped_column(String(3),nullable=True)
    salary_period: Mapped[str|None]=mapped_column(String(40),nullable=True)
    compensation_type: Mapped[str|None]=mapped_column(String(40),nullable=True)
    compensation_text: Mapped[str|None]=mapped_column(Text,nullable=True)
    benefits: Mapped[list]=mapped_column(JSON,default=list)
    required_skills: Mapped[list]=mapped_column(JSON,default=list)
    preferred_skills: Mapped[list]=mapped_column(JSON,default=list)
    programming_languages: Mapped[list]=mapped_column(JSON,default=list)
    tech_stack: Mapped[list]=mapped_column(JSON,default=list)
    education_requirements: Mapped[str|None]=mapped_column(Text,nullable=True)
    experience_min_months: Mapped[int|None]=mapped_column(Integer,nullable=True)
    graduation_years: Mapped[list]=mapped_column(JSON,default=list)
    visa_or_work_auth: Mapped[str|None]=mapped_column(Text,nullable=True)
    other_requirements: Mapped[list]=mapped_column(JSON,default=list)
    application_method: Mapped[str|None]=mapped_column(String(50),nullable=True)
    application_email: Mapped[str|None]=mapped_column(String(320),nullable=True)
    application_deadline: Mapped[datetime|None]=mapped_column(DateTime(timezone=True),nullable=True)
    raw_payload: Mapped[dict]=mapped_column(JSON,default=dict)
    content_hash: Mapped[str|None]=mapped_column(String(64),nullable=True,index=True)
    parser_version: Mapped[str|None]=mapped_column(String(40),nullable=True)
    data_quality_score: Mapped[float|None]=mapped_column(Numeric,nullable=True)
    status: Mapped[str]=mapped_column(String(30),default='unverified',index=True)
    first_seen_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now)
    last_seen_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now,onupdate=now)
    active: Mapped[bool]=mapped_column(Boolean,default=True,index=True)
    source: Mapped[Source]=relationship(back_populates='jobs')
    __table_args__=(UniqueConstraint('source_id','source_job_id',name='uq_job_source_id'),Index('ix_jobs_active_title','active','title'))
class ConnectorRun(Base):
    __tablename__='connector_runs'
    id: Mapped[int]=mapped_column(primary_key=True)
    source_id: Mapped[int|None]=mapped_column(ForeignKey('sources.id',ondelete='SET NULL'),nullable=True)
    connector: Mapped[str]=mapped_column(String(30))
    started_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now)
    finished_at: Mapped[datetime|None]=mapped_column(DateTime(timezone=True),nullable=True)
    fetched: Mapped[int]=mapped_column(default=0)
    inserted: Mapped[int]=mapped_column(default=0)
    updated: Mapped[int]=mapped_column(default=0)
    status: Mapped[str]=mapped_column(String(30),default='running')
    error: Mapped[str|None]=mapped_column(Text,nullable=True)

class JobSource(Base):
    __tablename__='job_sources'
    id: Mapped[int]=mapped_column(primary_key=True)
    job_id: Mapped[int]=mapped_column(ForeignKey('jobs.id',ondelete='CASCADE'),index=True)
    source_id: Mapped[int]=mapped_column(ForeignKey('sources.id',ondelete='CASCADE'),index=True)
    source_job_id: Mapped[str|None]=mapped_column(String(300),nullable=True)
    source_url: Mapped[str]=mapped_column(String(2000))
    apply_url: Mapped[str|None]=mapped_column(String(2000),nullable=True)
    first_seen_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now)
    last_seen_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now,onupdate=now)
    last_verified_at: Mapped[datetime|None]=mapped_column(DateTime(timezone=True),nullable=True)
    closed_at: Mapped[datetime|None]=mapped_column(DateTime(timezone=True),nullable=True)
    raw_payload: Mapped[dict]=mapped_column(JSON,default=dict)
    __table_args__=(UniqueConstraint('source_id','source_job_id',name='uq_job_source_external'),)

class JobSnapshot(Base):
    __tablename__='job_snapshots'
    id: Mapped[int]=mapped_column(primary_key=True)
    job_id: Mapped[int]=mapped_column(ForeignKey('jobs.id',ondelete='CASCADE'),index=True)
    content_hash: Mapped[str]=mapped_column(String(64),index=True)
    description: Mapped[str|None]=mapped_column(Text,nullable=True)
    raw_payload: Mapped[dict]=mapped_column(JSON,default=dict)
    captured_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now)

class Application(Base):
    __tablename__='applications'
    id: Mapped[int]=mapped_column(primary_key=True)
    job_id: Mapped[int]=mapped_column(ForeignKey('jobs.id',ondelete='CASCADE'),index=True)
    status: Mapped[str]=mapped_column(String(40),default='saved',index=True)
    notes: Mapped[str|None]=mapped_column(Text,nullable=True)
    applied_at: Mapped[datetime|None]=mapped_column(DateTime(timezone=True),nullable=True)
    created_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now)
    updated_at: Mapped[datetime]=mapped_column(DateTime(timezone=True),default=now,onupdate=now)
